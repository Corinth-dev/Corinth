import type { CcfField, CcfSchema } from "@skm/ccf-client";

/** Options of {@link generateTypes}. */
export interface TypegenOptions {
  /** Name of the root interface. Defaults to the PascalCase schema name. */
  rootName?: string;
  /** How `int64`/`uint64` fields are typed: `"number"` (default) or `"bigint"`. Match the client's `int64` option. */
  int64?: "number" | "bigint";
  /** How `decimal` fields are typed: `"number"` (default) or `"string"`. Match the client's `decimal` option. */
  decimal?: "number" | "string";
}

/**
 * Generates TypeScript interfaces for the rows of a schema. The root interface describes one row; nested objects
 * become `<Parent><Field>` interfaces and list elements that are objects become `<Parent><Field>Item`.
 */
export function generateTypes(schema: CcfSchema, options: TypegenOptions = {}): string {
  const rootName = options.rootName ?? pascal(schema.name);
  const used = new Set<string>();
  const emitted: string[] = [];

  const scalarType = (f: CcfField): string => {
    switch (f.type) {
      case "bool": return "boolean";
      case "int32": case "uint32": case "float64": return "number";
      case "int64": case "uint64": return options.int64 === "bigint" ? "bigint" : "number";
      case "decimal": return options.decimal === "string" ? "string" : "number";
      case "enum": return f.values!.map((v) => JSON.stringify(v)).join(" | ");
      case "string": case "guid": return "string";
      case "datetime": return "Date";
      default: throw new Error(`not a scalar: ${f.type}`);
    }
  };

  const unique = (name: string): string => {
    let candidate = name;
    for (let i = 2; used.has(candidate); i++) candidate = `${name}${i}`;
    used.add(candidate);
    return candidate;
  };

  /** The TypeScript type of a field's value, without the null for nullable fields. */
  const valueType = (f: CcfField, context: string): string => {
    if (f.type === "object") return emitInterface(unique(context + pascal(f.name)), f.fields!);
    if (f.type === "list") {
      const fields = f.fields!;
      if (fields.length === 1 && fields[0]!.name === "$value") {
        const element = fieldType(fields[0]!, context + pascal(f.name));
        return element.includes(" ") ? `(${element})[]` : `${element}[]`;
      }
      return `${emitInterface(unique(context + pascal(f.name) + "Item"), fields)}[]`;
    }
    return scalarType(f);
  };

  const fieldType = (f: CcfField, context: string): string => {
    const t = valueType(f, context);
    return f.nullable ? `${t} | null` : t;
  };

  const emitInterface = (name: string, fields: readonly CcfField[]): string => {
    const lines = fields.map((f) => `  ${propertyName(f.name)}: ${fieldType(f, name)};`);
    // Children are generated while building the lines above; the parent is recorded after them, then reordered so
    // parents come first.
    emitted.push(`export interface ${name} {\n${lines.join("\n")}\n}`);
    return name;
  };

  used.add(rootName);
  emitInterface(rootName, schema.fields);

  // `emitted` holds children before parents; print the root first, then the rest in order of appearance.
  const root = emitted[emitted.length - 1]!;
  const rest = emitted.slice(0, -1);
  const header = `// Generated by ccf-typegen from schema ${schema.idHex} (${schema.name}). Do not edit.\n`;
  return `${header}\n${[root, ...rest].join("\n\n")}\n`;
}

/** `snake_case`, `camelCase` and `kebab-case` to PascalCase. */
export function pascal(name: string): string {
  const parts = name.split(/[^A-Za-z0-9]+/).filter((p) => p.length > 0);
  const joined = parts.map((p) => p[0]!.toUpperCase() + p.slice(1)).join("");
  return /^[A-Za-z_]/.test(joined) ? joined : `_${joined}`;
}

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function propertyName(name: string): string {
  return IDENTIFIER.test(name) ? name : JSON.stringify(name);
}
